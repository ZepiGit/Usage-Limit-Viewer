//  OAuthFlows.swift
//  UsageLimitsKit
//
//  OAuth 2.0 login plumbing shared by every provider integration: the
//  authorisation-code flow with PKCE (RFC 7636) and the Device Authorization
//  Grant (RFC 8628).
//
//  Policy, stated up front: this kit only ever signs users in through a
//  provider's normal, published login flows. Nothing in this file scrapes
//  behind a login page, forges browser headers, or tries to get past a
//  CAPTCHA or bot check. If a provider's edge rejects an ordinary client,
//  the right response is to report that provider as unsupported — never to
//  disguise the request. The security decisions below (constant-time state
//  comparison, S256-only PKCE, a random source that refuses to degrade)
//  exist to protect the legitimate flow; they never attempt to defeat
//  anyone's protections.
//

